"""Pre-register experts who already have a profile in an earlier study, so they only sign in with email + access code.

Sources (repeatable, SOURCE is a free label stored in experts.source):
  --sqlite SOURCE=PATH   a study SQLite file with a `participants` table (e.g. cbt-live-interaction server/data/study.sqlite3)
  --json   SOURCE=PATH   a JSON list of participants (e.g. exported from cbt-simulator-evaluation)

Each participant needs: email, name, role, institution, latest_degree, years_experience (and profile_completed if present).
Duplicates across sources are merged by lower-cased email; the most recently active complete profile wins.

Output: data/experts.sql (PRIVATE, git-ignored). It inserts with ON CONFLICT DO NOTHING, so a profile already
present on the annotation site is never overwritten. Load it with:
  cd worker && npx wrangler d1 execute cbt_annotation --remote --file ../data/experts.sql

Example:
  python scripts/import_experts.py --json cbt-simulator-evaluation=data/simulator-evaluation-participants.json \
                                   --sqlite cbt-live-interaction=data/live-interaction-study.sqlite3
"""
from __future__ import annotations

import argparse
import json
import re
import sqlite3
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FIELDS = ("name", "role", "institution", "latest_degree")
EMAIL = re.compile(r"^[^\s@]+@[^\s@]+\.[^\s@]+$")


def labelled(value: str) -> tuple[str, Path]:
    if "=" not in value:
        raise argparse.ArgumentTypeError("use SOURCE=PATH")
    source, path = value.split("=", 1)
    return source.strip(), Path(path.strip())


def from_sqlite(path: Path) -> list[dict]:
    connection = sqlite3.connect(f"file:{path}?mode=ro", uri=True)
    connection.row_factory = sqlite3.Row
    columns = {row[1] for row in connection.execute("PRAGMA table_info(participants)")}
    rows = [dict(row) for row in connection.execute("SELECT * FROM participants")]
    if "profile_completed" not in columns:
        for row in rows:
            row["profile_completed"] = 1
    return rows


def from_json(path: Path) -> list[dict]:
    data = json.loads(path.read_text(encoding="utf-8"))
    return data.get("participants", data) if isinstance(data, dict) else data


def normalise(row: dict, source: str) -> dict | None:
    email = str(row.get("email") or "").strip().lower()
    if not EMAIL.match(email) or len(email) > 254:
        return None
    if "profile_completed" in row and not int(row.get("profile_completed") or 0):
        return None
    profile = {key: str(row.get(key) or "").strip() for key in FIELDS}
    if not all(profile.values()):
        return None
    try:
        years = int(row.get("years_experience"))
    except (TypeError, ValueError):
        return None
    if not 0 <= years <= 80:
        return None
    seen = str(row.get("last_seen_at") or row.get("created_at") or "")
    return {"email": email, **{k: v[:260] for k, v in profile.items()}, "years_experience": years, "source": source, "seen": seen}


def sql(value) -> str:
    return str(value) if isinstance(value, int) else "'" + str(value).replace("'", "''") + "'"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--sqlite", type=labelled, action="append", default=[])
    parser.add_argument("--json", type=labelled, action="append", default=[])
    parser.add_argument("--out", type=Path, default=ROOT / "data" / "experts.sql")
    args = parser.parse_args()
    if not args.sqlite and not args.json:
        parser.error("give at least one --sqlite or --json source")

    merged: dict[str, dict] = {}
    for kind, sources in (("sqlite", args.sqlite), ("json", args.json)):
        for source, path in sources:
            rows = from_sqlite(path) if kind == "sqlite" else from_json(path)
            kept = [p for p in (normalise(row, source) for row in rows) if p]
            print(f"{source}: {len(rows)} participants, {len(kept)} with a complete profile ({path})")
            for profile in kept:
                current = merged.get(profile["email"])
                if current is None or profile["seen"] > current["seen"]:
                    merged[profile["email"]] = profile

    stamp = datetime.now(timezone.utc).isoformat(timespec="milliseconds").replace("+00:00", "Z")
    lines = ["-- Generated by scripts/import_experts.py. Contains personal data: never commit."]
    for profile in sorted(merged.values(), key=lambda p: p["email"]):
        values = (profile["email"], profile["name"], profile["role"], profile["institution"], profile["latest_degree"],
                  profile["years_experience"], stamp, stamp, stamp, profile["source"])
        lines.append(
            "INSERT INTO experts (email, name, role, institution, latest_degree, years_experience, created_at, updated_at, "
            "last_seen_at, source) VALUES (" + ", ".join(map(sql, values)) + ") ON CONFLICT(email) DO NOTHING;"
        )
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(merged)} distinct experts -> {args.out}")
    for profile in sorted(merged.values(), key=lambda p: p["email"]):
        print(f"  {profile['email']:<40} {profile['name']:<30} {profile['source']}")


if __name__ == "__main__":
    main()
